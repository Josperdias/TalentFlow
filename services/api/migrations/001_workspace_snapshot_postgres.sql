-- Incremental PostgreSQL migration for an existing TalentFlow v0.5 database.
-- Prerequisites: companies, users and audit_logs already created by the base schema.
-- Run once after a verified backup. An empty database is created by SQLAlchemy.
BEGIN;
CREATE TABLE IF NOT EXISTS workspace_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id),
  data JSONB NOT NULL,
  version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
  updated_by INTEGER NOT NULL REFERENCES users(id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_workspace_company UNIQUE(company_id)
);
CREATE INDEX IF NOT EXISTS ix_workspace_snapshots_company_id ON workspace_snapshots(company_id);
COMMIT;
